def division_seed_rows() -> List[dict]:
    """转成 admin_division 表的行。"""
    import json

    rows = []
    for code, name, level, parent, aliases, poly in DIVISIONS:
        cx = sum(p[0] for p in poly) / len(poly)
        cy = sum(p[1] for p in poly) / len(poly)
        rows.append({
            "code": code,
            "name": name,
            "level": level,
            "parent_code": parent or None,
            "lat": cy,
            "lng": cx,
            "polygon": json.dumps([[round(x, 6), round(y, 6)] for x, y in poly], ensure_ascii=False),
            "aliases": json.dumps(aliases, ensure_ascii=False),
            "source": "self-built-mvp",
        })
    return rows


